class MayaNeuron:
    """Una neurona artificial que opera con aritmética vigesimal maya."""
    def __init__(self, in_features: int):
        self.weights: List[MayaScalar] = [
            MayaScalar(random.choice([-3, -2, -1, 1, 2, 3])) for _ in range(in_features)
        ]
        self.bias: MayaScalar = MayaScalar(0)
        self.last_inputs: List[MayaScalar] = []
        self.last_z: MayaScalar = MayaScalar(0)
        self.last_a: MayaScalar = MayaScalar(0)

    def forward(self, inputs: List[MayaScalar]) -> MayaScalar:
        self.last_inputs = inputs
        accum = MayaScalar(0)
        for w, x in zip(self.weights, inputs):
            accum = accum + (w * x)
        
        self.last_z = accum + self.bias
        
