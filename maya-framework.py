# 1. NÚCLEO ARITMÉTICO VIGESIMAL MAYA
# ======================================================================

class MayaScalar:
    """Escalar vigesimal entero representado con glifos biquinarios."""
    def __init__(self, val: int):
        self.val = int(val)
        self.sign = -1 if self.val < 0 else (1 if self.val > 0 else 0)
        mag = abs(self.val)
        
        self.levels: List[Tuple[int, int]] = []  # cada nivel guarda (barras, puntos)
        if mag == 0:
            self.levels.append((0, 0))
        else:
            while mag > 0:
                digit = mag % 20
                bars = digit // 5
                dots = digit % 5
                self.levels.append((bars, dots))
                mag //= 20

    @classmethod
    def from_bars_dots(cls, bars: int, dots: int, sign: int = 1):
        total = sign * (bars * 5 + dots)
        return cls(total)

    def glyph(self) -> str:
        """Renderiza el número en notación tradicional vertical."""
        if self.val == 0:
            return "[ 𝄐 (Caracol) ]"
        
        lines = []
        sign_str = "(-)" if self.sign < 0 else "(+)"
        lines.append(f"{sign_str} Total: {self.val}")
        
        for idx in reversed(range(len(self.levels))):
            bars, dots = self.levels[idx]
            d_str = ("• " * dots).strip() if dots > 0 else ""
            b_str = " | ".join(["——"] * bars) if bars > 0 else ""
            comp = f"{d_str} {b_str}".strip()
            if not comp:
                comp = "𝄐"
            lines.append(f"  20^{idx}: [ {comp} ]")
        return "\n".join(lines)

    def __add__(self, other: "MayaScalar") -> "MayaScalar":
        return MayaScalar(self.val + other.val)

    def __sub__(self, other: "MayaScalar") -> "MayaScalar":
        return MayaScalar(self.val - other.val)

    def __mul__(self, other: "MayaScalar") -> "MayaScalar":
        return MayaScalar(self.val * other.val)

